def data_names(result: DesignResult) -> tuple[str, ...]:
    """Nombres que vienen de los datos (redes, portón, buque, cabos): se permiten en español."""
    case = result.case
    names = [case.net.name, case.door.name, case.vessel.name or ""]
    if case.net_modified is not None:
        names.append(case.net_modified.name)
    names += [v.name or "" for v in case.vessel_class]
    return tuple(sorted({n for n in names if n}, key=len, reverse=True))


