def test_batch_report_and_exports_in_english(batch) -> None:  # type: ignore[no-untyped-def]
    import openpyxl

    from trawlkit.batch import result_xlsx, to_csv
    from trawlkit.report.batch import batch_html

    with use_lang("en"):
        page = batch_html(batch, generated=dt.date(2026, 1, 2))
        book = result_xlsx(batch)
        csv_text = to_csv(batch)
    p = parse(page)
    assert p.lang == "en"
    assert "Net projection to the fleet" in p.get("h1")
    assert "Summary" in p.get("h2")
    assert {"Vessel", "Status", "Scale", "Otter board", "Warp", "Cost"} <= set(p.get("th"))
