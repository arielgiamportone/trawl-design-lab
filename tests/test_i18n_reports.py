def test_tables_in_english(result: DesignResult) -> None:
    from trawlkit.report.construction import report_tables
    from trawlkit.report.tables import all_tables

    with use_lang("en"):
        tables = [*all_tables(result), *report_tables(result)]
    allowed = data_names(result)
    for table in tables:
        texts = [table.title, table.note, *(c.heading for c in table.columns)]
        keys = [c.key for c in table.columns]
        if keys == ["group", "name", "value", "unit"]:
            texts += [str(r[0]) for r in table.rows] + [str(r[1]) for r in table.rows]
        if table.key == "resumen":
            texts += [str(r[1]) for r in table.rows]
        assert_english(texts, allowed)
    summary = next(t for t in tables if t.key == "resumen")
    names = dict((r[0], r[1]) for r in summary.rows)
    assert names["headrope_m"] == "Headrope"
    assert names["footrope_m"] == "Footrope"
    assert names["solid_surface_m2"] == "Solid (twine) area (Ss)"
    panels = next(t for t in tables if t.key == "panos_std")
    sections = set(panels.column("section"))
    assert sections <= {"wingtip", "wing", "square", "belly", "body", "extension", "codend"}


def test_charts_in_english(result: DesignResult) -> None:
    from trawlkit.report.charts import all_charts

    with use_lang("en"):
        charts = all_charts(result)
    joined = "\n".join(charts.values())
    texts = [m for svg in charts.values() for m in re.findall(r">([^<>]+)</text>", svg)]
    texts += re.findall(r"<title>([^<]+)</title>", joined)
    assert_english(texts, data_names(result))
    assert "Available pull vs total drag" in joined
    assert "Towing speed [kn]" in joined
    assert "Drag of the standard net by method" in joined


def test_sheet_svg_in_english(result: DesignResult) -> None:
    from trawlkit.drawing import net_scale_svg, net_sheet_svg

    with use_lang("en"):
        sheet = net_sheet_svg(result, "std", year=2026)
        scale = net_scale_svg(result, "std")
    for svg, expected in (
        (sheet, ("UPPER PANEL (TOP)", "LOWER PANEL (BELLY)", "Fishing circle", "YEAR")),
        (scale, ("Graphic scale", "Hung dimensions per panel [m]", "Lengths")),
    ):
        for e in expected:
            assert e in svg, e
        texts = re.findall(r">([^<>]+)</text>", svg) + re.findall(r"<title>([^<]+)</title>", svg)
        assert_english(texts, data_names(result))
    # Decimales con punto en inglés (y coma en español).
    assert re.search(r"Total buoyancy = \d+ kgf", sheet)
    assert re.search(r"TOTAL LENGTH \d+\.\d\d m", sheet)
    assert re.search(r"LARGO TOTAL \d+,\d\d m", net_sheet_svg(result, "std", year=2026))


